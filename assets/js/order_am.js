// order_am.js - Պատվերների կառավարման համակարգ
document.addEventListener('DOMContentLoaded', function() {
    initializeOrdersSystem();
});

function initializeOrdersSystem() {
    displayOrders();
    setupOrderFilters();
}

function displayOrders(filter = 'all') {
    const orders = JSON.parse(localStorage.getItem('printingOrders') || '[]');
    const ordersContainer = document.getElementById('ordersContainer');
    const emptyState = document.getElementById('emptyOrdersState');
    
    if (!ordersContainer) return;
    
    let filteredOrders = orders;
    
    if (filter !== 'all') {
        filteredOrders = orders.filter(order => order.serviceType === filter);
    }
    
    // Սորտավորել ըստ ամսաթվի (նորերը վերևում)
    filteredOrders.sort((a, b) => b.timestamp - a.timestamp);
    
    if (filteredOrders.length === 0) {
        ordersContainer.innerHTML = '';
        if (emptyState) emptyState.style.display = 'block';
        return;
    }
    
    if (emptyState) emptyState.style.display = 'none';
    
    ordersContainer.innerHTML = filteredOrders.map(order => `
        <div class="order-card" data-order-id="${order.id}">
            <div class="order-header">
                <h4>Պատվեր #${order.id}</h4>
                <span class="order-status ${order.status}">${getStatusText(order.status)}</span>
            </div>
            <div class="order-body">
                <div class="order-info">
                    <p><strong>Ծառայություն:</strong> ${order.serviceName}</p>
                    <p><strong>Գումար:</strong> ${order.amount.toLocaleString('hy-AM')} AMD</p>
                    <p><strong>Վճարման եղանակ:</strong> ${getPaymentMethodText(order.paymentMethod)}</p>
                    <p><strong>Հեռախոս:</strong> ${order.phone}</p>
                    ${order.email ? `<p><strong>Էլ. փոստ:</strong> ${order.email}</p>` : ''}
                    <p><strong>Ամսաթիվ:</strong> ${order.date}</p>
                </div>
            </div>
            <div class="order-actions">
                <button class="btn-download" onclick="downloadReceipt('${order.id}')">
                    📥 Տպել անդորրագիր
                </button>
                <button class="btn-delete" onclick="deleteOrder('${order.id}')">
                    🗑️ Ջնջել
                </button>
            </div>
        </div>
    `).join('');
}

function setupOrderFilters() {
    const filterButtons = document.querySelectorAll('.filter-btn');
    filterButtons.forEach(btn => {
        btn.addEventListener('click', function() {
            const filter = this.getAttribute('data-filter');
            
            // Update active state
            filterButtons.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
            
            displayOrders(filter);
        });
    });
}

function getStatusText(status) {
    const statusMap = {
        'completed': '✅ Ավարտված',
        'pending': '⏳ Սպասում',
        'cancelled': '❌ Չեղարկված'
    };
    return statusMap[status] || status;
}

function getPaymentMethodText(method) {
    const methodMap = {
        'card': '💳 Բանկային քարտ',
        'idram': '📱 Idram',
        'telcell': '📞 TelCell'
    };
    return methodMap[method] || method;
}

